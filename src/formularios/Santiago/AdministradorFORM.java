    private void recargarUsuarios() {
        mt.setRowCount(0); // Limpia la tabla

        for (Usuario user : Usuario.getEmpleados()) {
            mt.addRow(new Object[]{
                user.getId(),
                user.getNombre(),
                user.getApellido(),
                user.getCargo()
            });
        }
    }
    
